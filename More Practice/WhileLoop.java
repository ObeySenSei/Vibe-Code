public class WhileLoop {

    public static void main(String[] args) {

        int num = 1;

        while (num <= 6) {
            System.out.println(num);
            num = num + 1; // num += 1
        }

        int i = 1; 
        do {
            System.out.println("Hello World");
        } while (i <= 4 );

        }
    }